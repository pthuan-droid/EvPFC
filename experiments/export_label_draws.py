"""Export the label draws of every run (labelled cells, the labels they were given, corrupted labels, hidden
types, cells whose view was removed) to label_draws/<data set>.npz.

All draws are generated by r2_core.make_setting from RandomState(1000 + seed), so this file only makes them
explicit; any script of this repository reproduces them exactly from the seed.

    python export_label_draws.py --datasets SLN111 CellMix ...        # uses cache/y_<ds>.npy or loads the data

Keys of <ds>.npz, for each seed s and setting t (frac1, frac5, frac10, noise20, hide2, miss30/50/70 on CellMix):
    s{s}_{t}_labelled      indices of the labelled cells
    s{s}_{t}_given         label given to them, as a code of the original annotation (y), wrong if corrupted
    s{s}_{t}_corrupted     indices of the labelled cells whose label was corrupted
    s{s}_{t}_hidden        codes (in y) of the hidden types
    s{s}_{t}_view_removed  indices of the cells whose second view was removed (missing-view runs)
    y                      the annotation used (integer codes); class_names if available
"""
import argparse, os, sys
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import r2_core as C  # noqa: E402
import r2_data  # noqa: E402

SETTINGS = {'frac1': dict(frac=0.01), 'frac5': dict(frac=0.05), 'frac10': dict(frac=0.10),
            'noise20': dict(frac=0.05, noise=0.2), 'hide2': dict(frac=0.05, hide=2)}
MISSING = {'miss30': 0.3, 'miss50': 0.5, 'miss70': 0.7}


def labels(ds, cache):
    f = os.path.join(cache, f'y_{ds}.npy')
    if os.path.exists(f):
        return np.load(f), None
    d = r2_data.load(ds)
    return d['y'], d.get('meta', {}).get('classes')


def main(a):
    os.makedirs(a.out, exist_ok=True)
    for ds in a.datasets:
        y, names = labels(ds, a.cache)
        classes = np.unique(y[y >= 0])
        out = dict(y=y.astype(np.int32))
        if names is not None:
            out['class_names'] = np.asarray(names).astype(str)
        sets = dict(SETTINGS)
        if ds == 'CellMix':
            sets.update({k: dict(frac=0.05, miss=v) for k, v in MISSING.items()})
        for seed in a.seeds:
            for t, s in sets.items():
                if s.get('hide') and len(classes) < 6:
                    continue
                st = C.make_setting(y, seed, s['frac'], noise=s.get('noise', 0.0), hide=s.get('hide', 0),
                                    miss=s.get('miss', 0.0))
                hidden = list(st['hidden'])
                order = [c for c in classes if c not in hidden] + hidden     # code space of st['yk']
                lab = np.where(st['lab'])[0]
                out[f's{seed}_{t}_labelled'] = lab.astype(np.int32)
                out[f's{seed}_{t}_given'] = np.asarray(order)[st['yk'][lab]].astype(np.int32)
                out[f's{seed}_{t}_corrupted'] = np.where(st['noisy'])[0].astype(np.int32)
                out[f's{seed}_{t}_hidden'] = np.asarray(hidden, dtype=np.int32)
                if s.get('miss'):
                    out[f's{seed}_{t}_view_removed'] = np.where(st['drop'])[0].astype(np.int32)
        np.savez_compressed(os.path.join(a.out, f'{ds}.npz'), **out)
        print(ds, len(y), 'cells,', len(classes), 'types ->', os.path.join(a.out, f'{ds}.npz'), flush=True)


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--data-root', default=os.environ.get('EVPFC_DATA', os.path.join(HERE, '..', 'datasets')))
    ap.add_argument('--cache', default=os.path.join(HERE, 'cache'))
    ap.add_argument('--out', default=os.path.join(HERE, '..', 'label_draws'))
    ap.add_argument('--datasets', nargs='*', default=['SLN111', 'SLN206', 'CellMix', 'ASAP_PBMC', 'BMMC_CITE',
                                                      'BMMC_Multiome', 'BMNC', 'Ma2020_1', 'PBMC10k_Multiome_feat', 'SMAGE3K'])
    ap.add_argument('--seeds', nargs='*', type=int, default=list(range(3, 13)))
    a = ap.parse_args()
    r2_data.set_root(a.data_root)
    main(a)
